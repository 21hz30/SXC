/** Translate one full string (already trimmed). Returns null if no match. */
export function translateString(s: string): string | null {
  if (!s || /[一-鿿]/.test(s)) return null; // already CJK / user Chinese
  const exact = DICT[s];
  if (exact) return exact;
  for (const [re, fn] of PATTERNS) {
    const m = s.match(re);
    if (m) {
      const out = fn(m);
      if (out && out !== s) return out;
    }
  }
  return null;
}

/** Like translateString but falls back to the input (for nested pattern use). */
function tr(s: string): string {
  const t = s.trim();
  return translateString(t) ?? t;
}

/** Public helper for client code (confirm dialogs etc.). */
export function tx(s: string, locale: Locale): string {
  if (locale !== "zh") return s;
  return translateString(s.trim()) ?? s;
}
