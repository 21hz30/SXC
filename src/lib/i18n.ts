/**
 * English ⇄ Chinese UI translation.
 *
 * Strategy: the app's source of truth stays English; a client runtime
 * (I18nRuntime) walks rendered text nodes + UI attributes and swaps any string
 * that matches this dictionary (exact match) or one of the patterns (composed
 * strings: counts, dates, names). Switching back to EN restores originals.
 *
 * Hard rules:
 *  - "Hyrox" is never translated (brand) — it simply never appears in a value.
 *  - User input is never touched: form field values are never rewritten, and
 *    user data only changes if it exactly equals a UI phrase (dictionary keys
 *    are full UI strings, case-sensitive, so collisions are rare).
 *  - Strings already containing CJK are skipped (user's Chinese stays as-is).
 */

export type Locale = "en" | "zh";
export const LOCALE_COOKIE = "sxc_locale";
export function isLocale(v: unknown): v is Locale {
  return v === "en" || v === "zh";
}

